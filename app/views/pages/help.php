    <h1>Ajuda</h1>
    <p class="muted">
        Dr. Newsletter é uma plataforma de planejamento e escrita de
        newsletters para negócios presenciais premium.
    </p>

    <section class="card">
        <h2 style="margin-top:0">Fluxo do produto</h2>
        <ol class="help-steps">
            <li>
                <strong>Criar um cliente.</strong>
                <p class="muted small">Em “Clientes → Novo cliente”. Nome do negócio,
                segmento (joalheria, restaurante, clínica, ótica, outro). Email
                de contato é opcional.</p>
            </li>
            <li>
                <strong>Subir a Voz da Marca.</strong>
                <p class="muted small">Em “Cliente → Voz da Marca”. Um TXT (UTF-8)
                descrevendo tom de voz, público, valores, temas preferidos e
                temas a evitar. A IA estrutura automaticamente em JSON. Cada
                novo upload cria uma versão; o histórico fica preservado.</p>
            </li>
            <li>
                <strong>Subir o Arquivo de Emails.</strong>
                <p class="muted small">Em “Cliente → Arquivo de Emails”. Até 5 TXTs
                com exemplos de emails já enviados pelo cliente. A IA usa como
                referência de tom e estrutura, sem copiar literalmente.</p>
            </li>
            <li>
                <strong>Gerar o planejamento mensal.</strong>
                <p class="muted small">Em “Cliente → Planejador”. Escolha mês, ano,
                e quantidade de emails (1–31). A IA gera N temas estruturados
                distribuídos entre 5 categorias (educação, história, bastidor,
                estilo de vida, convite). Demora 10–30 segundos.</p>
            </li>
            <li>
                <strong>Adicionar temas avulsos</strong> (opcional).
                <p class="muted small">No detalhe do plano, gere mais temas com
                foco específico. Os temas existentes não são repetidos.</p>
            </li>
            <li>
                <strong>Escrever cada email.</strong>
                <p class="muted small">Em cada tema, clique em “Escrever email →”.
                A IA gera 3 opções de subject, preview, body e P.S. Você pode
                pedir nova versão no chat: “Mais curto”, “Muda o gancho”, etc.
                Cada turno gera nova versão; histórico preservado.</p>
            </li>
            <li>
                <strong>Aprovar e exportar.</strong>
                <p class="muted small">Ao aprovar o email, ele fica marcado como
                pronto. Exporte como TXT para colar em Mailchimp, RD, AC ou
                qualquer ferramenta de envio.</p>
            </li>
        </ol>
    </section>

    <section class="card">
        <h2 style="margin-top:0">Boas práticas</h2>
        <ul>
            <li><strong>Voz da Marca de qualidade</strong> é o input mais
                importante. Quanto mais específico, melhor o output.</li>
            <li><strong>Arquivo de Emails</strong> ajuda muito o tom — mas
                a IA segue as instruções de “DONTS” da voz mesmo quando o
                arquivo contém frases proibidas.</li>
            <li><strong>Feedback iterativo</strong> no escritor é onde a
                mágica acontece. Diga o que está ruim, não só “pior agora”.</li>
            <li><strong>Custo</strong>: planejamento mensal e email completo
                custam centavos de dólar cada. O painel mostra o total.</li>
        </ul>
    </section>

