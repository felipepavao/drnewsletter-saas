    <h2>Como funciona</h2>
    <p>
        Dr. Newsletter é uma plataforma de planejamento e escrita de
        newsletters para negócios presenciais premium. O fluxo é:
    </p>
    <ol>
        <li>Crie um cliente.</li>
        <li>Suba o TXT da Voz da Marca dele.</li>
        <li>Suba até 5 TXTs com exemplos de emails (referência de tom).</li>
        <li>Gere o planejamento mensal — 4 a 8 temas estruturados.</li>
        <li>A partir de cada tema, gere o email completo com chat iterativo.</li>
        <li>Aprove e exporte.</li>
    </ol>

